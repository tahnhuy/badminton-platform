import { Router } from 'express';
import { authenticate, requireRole } from '../../middleware/auth.middleware';
import { validate } from '../../middleware/validate.middleware';
import * as v from '../../validation/owner';
import { ownerController as c } from '../../controllers/owner/OwnerController';
const router = Router();
router.use(authenticate, requireRole('COURT_OWNER'));
const params = v.ownerIdParams;
router.get('/facilities', validate({ query: v.ownerPage }), c.facilities);
router.post('/facilities', validate({ body: v.ownerFacilityBody }), c.createFacility);
router.get('/facilities/:id', validate({ params }), c.detail);
router.put('/facilities/:id', validate({ params, body: v.ownerFacilityUpdate }), c.updateFacility);
router.post('/facilities/:id/resubmit', validate({ params, body: v.ownerEmptyBody }), c.resubmitFacility);
router.post('/facilities/:id/address-change-requests', validate({ params, body: v.ownerLocationBody }), c.addressChange);
router.get('/facilities/:id/reviews', validate({ params, query: v.ownerPage }), c.facilityReviews);
router.post('/facilities/:id/courts', validate({ params, body: v.ownerCourtBody }), c.createCourt);
router.put('/courts/:id', validate({ params, body: v.ownerCourtBody }), c.updateCourt);
router.post('/courts/:id/resubmit', validate({ params, body: v.ownerEmptyBody }), c.resubmitCourt);
router.get('/courts/:id/reviews', validate({ params, query: v.ownerPage }), c.courtReviews);
router.get('/courts/:id/pricings', validate({ params, query: v.ownerPricingQuery }), c.pricing);
router.post('/courts/:id/pricings', validate({ params, body: v.ownerPricingBody }), c.savePricing);
router.get('/facilities/:id/schedule', validate({ params, query: v.ownerScheduleQuery }), c.schedule);
router.get('/facilities/:id/bookings', validate({ params, query: v.ownerHistoryQuery }), c.bookingHistory);
router.get('/bookings/:id', validate({ params }), c.bookingDetail);
router.post('/courts/:id/block-slots', validate({ params, body: v.ownerBlockBody }), c.block);
router.post('/courts/:id/unblock-slots', validate({ params, body: v.ownerUnblockBody }), c.unblock);
export default router;
